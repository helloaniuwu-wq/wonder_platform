#!/usr/bin/env python3
"""
export-d1.py — 将 backend/hk_admin.db 中需要保留的数据导出为 100% Cloudflare D1 兼容的纯标准 SQL
"""
import sqlite3
import os
import json
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parents[3]
DB_PATH = ROOT_DIR / "backend" / "hk_admin.db"
OUT_SQL = ROOT_DIR / "apps" / "api-worker" / "migrations" / "0002_seed_data.sql"

TABLES_TO_EXPORT = [
    "users",
    "companies",
    "user_company_access",
    "company_tax_profiles",
    "clients",
    "invoices",
    "invoice_items",
    "payments",
    "expense_categories",
    "expenses",
    "commission_statements",
    "ir56m_statements",
    "compliance_items",
    "portfolios",
    "transactions",
    "manual_dividends",
    "portfolio_stats_cache",
    "assets",
    "advisor_clients",
    "insurance_plans",
    "lab_scenarios",
    "user_ilp_config",
]

CUSTOM_QUERIES = {
    "user_company_access": """
        SELECT * FROM user_company_access 
        WHERE user_id IN (SELECT id FROM users) 
          AND company_id IN (SELECT id FROM companies)
    """
}

def escape_val(val):
    if val is None:
        return "NULL"
    elif isinstance(val, (int, float)):
        return str(val)
    elif isinstance(val, (bytes, bytearray)):
        return f"X'{val.hex()}'"
    else:
        # 字符串转义：SQLite 标准是将单引号替换为两个单引号
        s = str(val).replace("'", "''")
        return f"'{s}'"

def main():
    if not DB_PATH.exists():
        print(f"❌ 找不到数据库: {DB_PATH}")
        return

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    lines = [
        "-- =============================================================",
        "-- Wonder Platform — Cloudflare D1 Seed Data (Cleaned & Standard SQL)",
        "-- Auto-generated by export-d1.py",
        "-- =============================================================",
        "PRAGMA foreign_keys = OFF;",
        "",
    ]

    for table in TABLES_TO_EXPORT:
        query = CUSTOM_QUERIES.get(table, f"SELECT * FROM {table}")
        try:
            cursor.execute(query)
            rows = cursor.fetchall()
            col_names = [d[0] for d in cursor.description]

            if not rows:
                print(f"⚪ 表 [{table}] 为空，跳过")
                continue

            lines.append(f"-- ── Table: {table} ({len(rows)} rows) ──")
            cols_str = ", ".join([f'"{c}"' for c in col_names])

            for row in rows:
                vals_str = ", ".join([escape_val(v) for v in row])
                lines.append(f"INSERT OR REPLACE INTO {table} ({cols_str}) VALUES ({vals_str});")

            lines.append("")
            print(f"✅ 导出表 [{table}]: {len(rows)} 行")
        except sqlite3.OperationalError as e:
            print(f"⚠️ 跳过表 [{table}]: {e}")

    conn.close()

    lines.append("PRAGMA foreign_keys = ON;")
    lines.append("")

    with open(OUT_SQL, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"\n🎉 成功生成标准 D1 数据文件: {OUT_SQL}")

if __name__ == "__main__":
    main()
